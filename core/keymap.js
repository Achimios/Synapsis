// >v<⌨快捷键-搜键位-快捷键页左边那个框：按一下键（含组合）就查有哪些条目用到它（👤 2026-10-10）
// 纯函数、不碰浏览器：comboFromKeyEvent 把按键事件变成 {mods, key}；matchKey 看某条键位文字里有没有这个组合
const MOD_ORDER = ['Ctrl', 'Alt', 'Shift', 'Win'];
const KEY_ALIAS = { arrowup: ['↑'], arrowdown: ['↓'], arrowleft: ['←'], arrowright: ['→'], ' ': ['空格', 'space'], delete: ['del', 'delete'], escape: ['esc'], '`': ['`', '反引号'], enter: ['enter'], tab: ['tab'], insert: ['insert'], backspace: ['backspace'] };
export function comboFromKeyEvent(e) {
  const k = e.key;
  if (!k || ['Control', 'Shift', 'Alt', 'Meta', 'Process', 'Dead'].includes(k)) return null; // 只按了修饰键：抬起时再记（界面处理）
  const mods = [];
  if (e.ctrlKey) mods.push('Ctrl');
  if (e.altKey) mods.push('Alt');
  const symbol = k.length === 1 && !/[a-z0-9]/i.test(k); // ? ! 这类要按 Shift 才出来的符号：Shift 不算（表里写的是 ? 不是 Shift+?）
  if (e.shiftKey && !symbol) mods.push('Shift');
  if (e.metaKey) mods.push('Win');
  return { mods, key: k.length === 1 ? k.toLowerCase() : k };
}
export const comboText = c => c ? [...c.mods, c.key == null ? null : ({ ArrowUp: '↑', ArrowDown: '↓', ArrowLeft: '←', ArrowRight: '→', ' ': 'Space' }[c.key] || (c.key.length === 1 ? c.key.toUpperCase() : c.key))].filter(Boolean).join('+') : '';
const tokensOf = text => new Set(String(text).toLowerCase().split(/[\s+/·,，、()（）「」]+/).filter(Boolean));
export function matchKey(entryKey, combo) {
  if (!combo) return true;
  const t = tokensOf(entryKey);
  if (!combo.mods.every(m => t.has(m.toLowerCase()))) return false;
  if (combo.key == null) return true;
  const kk = combo.key.toLowerCase();
  return (KEY_ALIAS[kk] || [kk]).some(a => t.has(a));
}
