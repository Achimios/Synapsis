// >v<🚀启停-启动器-项目根只放一个带图标的快捷方式「在Synapsis打开本项目.lnk」；兜底的 vbs 藏进 .synapsis/（👤 2026-10-08）
//   快捷方式 → wscript .synapsis/Synapsis.vbs → 有 Electron 就开客户端，没有就 dev 服务 + 浏览器
//   图标都在 <Synapsis>/_图标/：项目.ico（快捷方式）/ 客户端.ico + 客户端.png（客户端快捷方式、托盘、窗口）。
//   换图标：把图丢给 core/tools/make_icon.py，或者右键快捷方式 → 属性 → 更改图标 → 选 _图标/ 里的 .ico
//   .lnk 里是本机绝对路径 → 不进 git；没有就补（打开工作区时 / init / 客户端启动时）
import { readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

export const HOME = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const ICON_DIR = join(HOME, '_图标');
export const PROJECT_LNK = '在Synapsis打开本项目.lnk';
export const CLIENT_LNK = 'Synapsis 客户端.lnk';
const VBS = join('.synapsis', 'Synapsis.vbs');
const OLD_HEADER = "' Synapsis launcher for this project (generated by";

// 用 WScript.Shell 建快捷方式。PowerShell 5.1 + 中文路径 → 路径全走环境变量（Unicode），命令本身纯 ASCII
export function makeShortcut(lnk, target, args, icon, cwd) {
  if (process.platform !== 'win32' || process.env.SYN_NO_LNK) return false;
  const ps = "$s=(New-Object -ComObject WScript.Shell).CreateShortcut($env:SYN_L);$s.TargetPath=$env:SYN_T;$s.Arguments=$env:SYN_A;$s.WorkingDirectory=$env:SYN_W;if(Test-Path -LiteralPath $env:SYN_I){$s.IconLocation=$env:SYN_I+',0'};$s.Save()";
  const r = spawnSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', ps], { env: { ...process.env, SYN_L: lnk, SYN_T: target, SYN_A: args, SYN_W: cwd, SYN_I: icon }, windowsHide: true });
  return r.status === 0 && existsSync(lnk);
}

const wscript = () => join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'wscript.exe');

// 生成 / 刷新项目启动器。force = 快捷方式已有也重建（换了图标后）。返回做了什么
export function ensureLauncher(root, { force = false } = {}) {
  const made = [];
  const vbs = join(root, VBS);
  const fresh = readFileSync(join(HOME, 'core', 'templates', 'Synapsis.vbs'), 'utf8').split('{{SYNAPSIS_HOME}}').join(HOME);
  mkdirSync(dirname(vbs), { recursive: true });
  if (!existsSync(vbs) || readFileSync(vbs, 'utf8') !== fresh) { writeFileSync(vbs, fresh); made.push(VBS); }
  // 旧版放在项目根的 Synapsis.vbs（是生成物，认得出头部才动）→ 去掉，由快捷方式替代
  const old = join(root, 'Synapsis.vbs');
  if (existsSync(old) && readFileSync(old, 'utf8').startsWith(OLD_HEADER)) { rmSync(old); made.push('去掉根目录旧的 Synapsis.vbs'); }
  const lnk = join(root, PROJECT_LNK);
  if ((force || !existsSync(lnk)) && makeShortcut(lnk, wscript(), `"${vbs}"`, join(ICON_DIR, '项目.ico'), root)) made.push(PROJECT_LNK);
  if (resolve(root) === HOME) { // Synapsis 自己的目录：再放一个开客户端的
    const c = join(HOME, CLIENT_LNK);
    if ((force || !existsSync(c)) && makeShortcut(c, wscript(), `"${join(HOME, 'app', 'Synapsis_desktop.vbs')}"`, join(ICON_DIR, '客户端.ico'), HOME)) made.push(CLIENT_LNK);
  }
  return made;
}
